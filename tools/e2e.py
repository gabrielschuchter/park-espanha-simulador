import json, sys, time, os
from playwright.sync_api import sync_playwright
URL = 'file://' + os.path.abspath('dist/index.html')
OUT = 'tools/shots'
errors = []
def log(*a): print(*a, flush=True)
with sync_playwright() as p:
    b = p.chromium.launch(args=["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader","--ignore-gpu-blocklist"])
    ctx = b.new_context(viewport={'width':1680,'height':960}, device_scale_factor=1)
    pg = ctx.new_page()
    pg.on('console', lambda m: errors.append(f'{m.type}: {m.text}') if m.type in ('error','warning') else None)
    pg.on('pageerror', lambda e: errors.append(f'pageerror: {e}'))
    pg.goto(URL); pg.wait_for_timeout(800)
    pg.screenshot(path=f'{OUT}/01-home.png', full_page=True)
    pg.click('[data-novo="meio"][data-sug="1"]'); pg.wait_for_timeout(2500)
    pg.screenshot(path=f'{OUT}/02-meio-split.png')
    st = pg.evaluate("() => ({n: __pe.store.projeto.itens.length, alertas: __pe.analise().alertas.length, bloq: __pe.analise().circ.bloqueios.length})")
    log('meio', st)
    # adicionar cama de casal pelo catálogo
    pg.click('[data-cat="quarto"]'); pg.click('[data-add="camacasal"]'); pg.wait_for_timeout(400)
    cama = pg.evaluate("() => { const it = __pe.store.projeto.itens.at(-1); return {uid: it.uid, w: it.w, d: it.d, x: it.x, y: it.y, nome: it.nome}; }")
    log('cama', cama)
    # arrastar a cama na planta
    box = pg.evaluate(f"() => {{ const g = document.querySelector('[data-uid=\"{cama['uid']}\"]'); const r = g.getBoundingClientRect(); return [r.x + r.width/2, r.y + r.height/2]; }}")
    pg.mouse.move(*box); pg.mouse.down(); pg.mouse.move(box[0]+60, box[1]+30, steps=8); pg.mouse.up(); pg.wait_for_timeout(500)
    c2 = pg.evaluate(f"() => {{ const it = __pe.store.projeto.itens.find(i=>i.uid=='{cama['uid']}'); const m = __pe.view3d.meshPos(it.uid); return {{x: it.x, y: it.y, mx: m.x, mz: m.z, rot: it.rot, mrot: m.rotY}}; }}")
    log('cama após arrastar (2D vs 3D)', c2)
    pg.screenshot(path=f'{OUT}/03-cama-arrastada.png')
    # sofá 2,20 e distância
    pg.click('[data-cat="sala"]'); pg.click('[data-add="sofa3"]'); pg.wait_for_timeout(500)
    insp = pg.evaluate("() => [...document.querySelectorAll('#i-dist input')].map(i=>[i.id,i.value])")
    log('distâncias sofá', insp, pg.evaluate("() => { const it=__pe.store.projeto.itens.at(-1); return [it.w,it.d]; }"))
    # editar distância: fundo = 0
    pg.fill('#i-dist-0\\,-1', '0'); pg.press('#i-dist-0\\,-1', 'Enter'); pg.wait_for_timeout(400)
    log('após fundo=0', pg.evaluate("() => [...document.querySelectorAll('#i-dist input')].map(i=>[i.id,i.value])"))
    # rotação, undo
    pg.keyboard.press('Escape'); 
    pg.evaluate("() => __pe.setView('3d')"); pg.wait_for_timeout(1500)
    pg.screenshot(path=f'{OUT}/04-3d-maquete.png')
    pg.click('[data-modo="cima"]'); pg.wait_for_timeout(1200); pg.screenshot(path=f'{OUT}/05-3d-cima.png')
    pg.click('[data-modo="passeio"]'); pg.wait_for_timeout(1000)
    p0 = pg.evaluate("() => __pe.view3d.info()")
    pg.screenshot(path=f'{OUT}/06-passeio-inicio.png')
    pg.mouse.move(900,450); pg.keyboard.down('KeyW'); pg.wait_for_timeout(1800); pg.keyboard.up('KeyW')
    p1 = pg.evaluate("() => __pe.view3d.info()")
    log('passeio', p0['pos'], '->', p1['pos'], 'drawcalls', p1['calls'], 'tris', p1['tris'])
    pg.screenshot(path=f'{OUT}/07-passeio-andou.png')
    pg.select_option('#ir-para', 'q2'); pg.wait_for_timeout(800); pg.screenshot(path=f'{OUT}/08-passeio-q2.png')
    pg.select_option('#ir-para', 'b1'); pg.wait_for_timeout(800); pg.screenshot(path=f'{OUT}/09-passeio-b1.png')
    pg.click('[data-luz="noite"]'); pg.select_option('#ir-para', 'sala'); pg.wait_for_timeout(800); pg.screenshot(path=f'{OUT}/10-noite-sala.png')
    n_antes = pg.evaluate("() => __pe.store.projeto.itens.length")
    pg.wait_for_timeout(800)
    # recarregar
    pg.reload(); pg.wait_for_timeout(800)
    lst = pg.evaluate("() => [...document.querySelectorAll('#proj-list .nome')].map(e=>e.textContent)")
    pg.click('[data-abrir]'); pg.wait_for_timeout(1500)
    n_depois = pg.evaluate("() => __pe.store.projeto.itens.length")
    log('persistência', lst, n_antes, '->', n_depois)
    # Ponta
    pg.click('#btn-voltar'); pg.wait_for_timeout(300)
    pg.click('[data-novo="ponta"][data-sug="1"]'); pg.wait_for_timeout(2500)
    log('ponta', pg.evaluate("() => ({n: __pe.store.projeto.itens.length, alertas: __pe.analise().alertas.map(a=>a.msg), bloq: __pe.analise().circ.bloqueios.length})"))
    pg.screenshot(path=f'{OUT}/11-ponta-split.png')
    pg.evaluate("() => __pe.setView('2d')"); pg.wait_for_timeout(500)
    pg.screenshot(path=f'{OUT}/12-ponta-2d.png')
    # mobile
    m = b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2, is_mobile=True, has_touch=True)
    mp = m.new_page(); mp.on('pageerror', lambda e: errors.append(f'mobile pageerror: {e}'))
    mp.goto(URL); mp.wait_for_timeout(600); mp.screenshot(path=f'{OUT}/20-m-home.png')
    mp.tap('[data-novo="meio"][data-sug="1"]'); mp.wait_for_timeout(1500); mp.screenshot(path=f'{OUT}/21-m-editor.png')
    mp.tap('#bb-cat'); mp.wait_for_timeout(500); mp.screenshot(path=f'{OUT}/22-m-catalogo.png')
    mp.tap('[data-add="poltrona"]'); mp.wait_for_timeout(600); mp.screenshot(path=f'{OUT}/23-m-sel.png')
    mp.tap('#bb-view'); mp.wait_for_timeout(1800); mp.tap('[data-modo="passeio"]'); mp.wait_for_timeout(1000); mp.screenshot(path=f'{OUT}/24-m-passeio.png')
    mp.tap('#bb-view'); mp.wait_for_timeout(600); mp.screenshot(path=f'{OUT}/25-m-planta-girada.png')
    log('rot mobile', mp.evaluate("() => __pe.plan2d.view"))
    sw = mp.evaluate("() => document.documentElement.scrollWidth - innerWidth")
    log('overflow horizontal mobile', sw)
    b.close()
log('ERROS:', json.dumps(errors[:20], ensure_ascii=False, indent=1))
